#include "../push_swap.h"

int	ft_push(t_stack **x, t_stack **y)
{
	t_stack	*swap;

	if (!y)
		return (1);
	swap = *y;
	*y = (*y)->next;
	swap->next = (*x);
	*x = swap;
	return (1);
}
